// Copies the Blog Template (drthomasager.com assets/blog/blog.css, the base template
// for every blog) into this app as css/blog-template.css, scoped under .bt so its
// element rules (h1, p, a, table...) only touch a post, never the app around it.
//
//   node scripts/blog-template-sync.mjs [path/to/blog.css]
//
// Default source: ../drthomasager/drthomasager.com/assets/blog/blog.css
// Rules for the page frame (.page, .progress, .toolbar, body, html) are dropped:
// the app frames the post itself. :root becomes .bt; [data-theme="night"] is dropped
// because the app is light Aero. css/blog-aero.css then lays the template's tokens
// onto the Aero glass.
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2] || new URL('../../drthomasager/drthomasager.com/assets/blog/blog.css', import.meta.url).pathname;
const css = readFileSync(src, 'utf8');

// Split into top-level blocks: [prelude, body] with @media bodies recursed.
function blocks(text) {
  const out = []; let i = 0;
  while (i < text.length) {
    const open = text.indexOf('{', i); if (open < 0) break;
    let depth = 1, j = open + 1;
    while (j < text.length && depth) { if (text[j] === '{') depth++; else if (text[j] === '}') depth--; j++; }
    out.push([text.slice(i, open).trim(), text.slice(open + 1, j - 1)]); i = j;
  }
  return out;
}
const stripComments = t => t.replace(/\/\*[\s\S]*?\*\//g, '');
const DROP = /^(\.page|\.progress|\.toolbar|html|body|::selection|\*)\b/;
function scopeSel(sel) {
  return sel.split(',').map(s => s.trim()).filter(Boolean).map(s => {
    if (s === ':root') return '.bt';
    if (s.startsWith(':root[')) return null;
    if (DROP.test(s)) return null;
    return '.bt ' + s;
  }).filter(Boolean).join(',');
}
function render(text, indent = '') {
  let out = '';
  for (const [pre, body] of blocks(stripComments(text))) {
    if (pre.startsWith('@media')) { const inner = render(body, indent + '  '); if (inner.trim()) out += `${indent}${pre}{\n${inner}${indent}}\n`; continue; }
    const sel = scopeSel(pre); if (!sel) continue;
    out += `${indent}${sel}{${body.trim()}}\n`;
  }
  return out;
}

const head = `/* GENERATED by scripts/blog-template-sync.mjs from the Blog Template
   (DrThomasAger/drthomasager.com, assets/blog/blog.css: "the base template for all
   blogs"). Do not edit here: edit the template and run the script again.
   Every rule is scoped under .bt. Its colours are laid onto Aero glass in css/blog-aero.css. */\n`;
writeFileSync(new URL('../css/blog-template.css', import.meta.url), head + render(css));
console.log('wrote css/blog-template.css from', src);
