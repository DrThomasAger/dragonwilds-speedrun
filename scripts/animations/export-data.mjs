// export-data.mjs — dump the real data the manim scenes animate.
//
//   node scripts/animations/export-data.mjs [--n 20000]
//
// Reads js/data/raid.js (RUNS, SPLITS, targetPace, communityBest) and the
// Monte-Carlo model in scripts/analysis/ (in memory; writes nothing there).
// Writes data/kb/prior/animation-data.json, which scripts/animations/*.py read.
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RUNS, SPLITS, RECORD, TARGET_TIME, targetPace, communityBest } from '../../js/data/raid.js';
import * as M from '../analysis/model.mjs';
// model.mjs is under active development; read what it exports instead of pinning names.
const { buildModel, DEFAULT_CURRENT_ROUTE, sampleSegment, routeVariants, SEED, N_SPLITS } = M;
const asRunFor = id => (M.AS_RUN && M.AS_RUN[id]) || M.AS_RUN_ROUTE || null;
import { simulate } from '../analysis/simulate.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const nArg = process.argv.indexOf('--n');
const N = nArg > 0 ? +process.argv[nArg + 1] : 20000;
const r2 = x => Math.round(x * 100) / 100;

const model = buildModel();
const mc = [];
for (const id of ['tp650', 'nano701']) {
  const prof = model.profiles.find(p => p.id === id);
  for (const [routeName, route] of [['as-run', asRunFor(id)], ['current', DEFAULT_CURRENT_ROUTE]].filter(x => x[1])) {
    const s = simulate(prof, route, { n: N });
    mc.push({ profile: id, label: prof.label, routeName, route, n: N, pBeat: s.pBeat, pFinish: s.pFinish, median: r2(s.median), p10: r2(s.p10), p90: r2(s.p90) });
  }
}
// Finished-time samples for the histogram (both reference profiles, as-run and current-patch routes).
// Same counter-based randoms (seed, i) as simulate(), so these match its summary.
function samples(prof, route, n) {
  const vs = routeVariants(route), out = []; let dead = 0;
  for (let i = 0; i < n; i++) {
    let t = 0, d = false;
    for (let k = 0; k < N_SPLITS; k++) { const s = sampleSegment(prof, k, vs[k], SEED, i, null); t += s.t; if (s.dead) { d = true; break; } }
    if (d) dead++; else out.push(r2(t));
  }
  return { finished: out, dead };
}
const hist = {};
for (const id of ['tp650', 'nano701']) {
  const prof = model.profiles.find(p => p.id === id);
  if (asRunFor(id)) hist[`${id}:as-run`] = { route: asRunFor(id), ...samples(prof, asRunFor(id), N) };
  hist[`${id}:current`] = { route: DEFAULT_CURRENT_ROUTE, ...samples(prof, DEFAULT_CURRENT_ROUTE, N) };
}

const out = {
  _note: 'Generated by scripts/animations/export-data.mjs from js/data/raid.js and scripts/analysis/model.mjs (seeded Monte Carlo, modelled not observed).',
  generatedAt: new Date().toISOString(),
  splits: SPLITS.map(s => s.short),
  record: RECORD, targetTime: TARGET_TIME, targetPace: targetPace().map(r2),
  runs: RUNS.map(r => ({ key: r.key, runner: r.runner, label: r.label, time: r.time, splits: r.splits })),
  communityBest: communityBest().map(b => ({ seg: r2(b.seg), run: b.run, runner: b.runner })),
  sumOfBest: r2(communityBest().reduce((a, b) => a + b.seg, 0)),
  monteCarlo: { currentRoute: DEFAULT_CURRENT_ROUTE, summary: mc, samples: hist },
};
writeFileSync(join(root, 'data/kb/prior/animation-data.json'), JSON.stringify(out));
console.log('sumOfBest', out.sumOfBest, 'targetPace', out.targetPace.join(' '));
for (const m of mc) console.log(m.profile, m.routeName, 'pBeat', m.pBeat.toFixed(4), 'median', m.median, 'p10', m.p10);
for (const [k, v] of Object.entries(hist)) console.log(k, 'finished', v.finished.length, 'dead', v.dead);
